CREATE TABLE LANCAMENTOS (
    ID               SERIAL        NOT NULL,
    USERS_ID          INT8          NOT NULL,
    DT_LANCAMENTO    TIMESTAMP     NOT NULL,
    VALOR            NUMERIC(8, 2) NOT NULL,
    TP_LANCAMENTO    VARCHAR(1)    NOT NULL,
    TP_DESPESA VARCHAR(200),
    OBSERVACAO       VARCHAR(1000),
    CONSTRAINT LANCAMENTO_PK PRIMARY KEY (ID),
    CONSTRAINT LANCAMENTO_USER_FK FOREIGN KEY (USERS_ID) REFERENCES USERS (ID),
    CONSTRAINT LANCAMENTOS_CHECK_TP_LANC CHECK (TP_LANCAMENTO IN ('C', 'D'))
);
